/* ── Clip check ── */
static inline int clip_test(gfx_ctx_t* ctx, int32_t x, int32_t y)
{
    return (x >= (int32_t)ctx->clip_x && x < (int32_t)ctx->clip_x2 &&
            y >= (int32_t)ctx->clip_y && y < (int32_t)ctx->clip_y2);
}

static inline int clip_test_u(gfx_ctx_t* ctx, uint32_t x, uint32_t y)
{
    return (x >= ctx->clip_x && x < ctx->clip_x2 &&
            y >= ctx->clip_y && y < ctx->clip_y2);
}

/* ── Pixel ── */
void gfx_putpixel(gfx_ctx_t* ctx, int32_t x, int32_t y, uint32_t c)
{
    if (!ctx || !ctx->fb) return;
    if (x < 0 || y < 0 || x >= (int32_t)ctx->width || y >= (int32_t)ctx->height) return;
    if (!clip_test(ctx, x, y)) return;

    if ((c >> 24) == 0xFF)
        ctx->fb[y * ctx->width + x] = c;
    else if ((c >> 24) != 0)
        ctx->fb[y * ctx->width + x] = gfx_blend(ctx->fb[y * ctx->width + x], c);
}

/* ── Alpha blend ── */
uint32_t gfx_blend(uint32_t dst, uint32_t src)
{
    uint8_t sa = src >> 24;
    if (sa == 0)   return dst;
    if (sa == 255) return src;

    uint8_t da = 255 - sa;
    uint8_t r = ((src >> 16) & 0xFF) * sa / 255 + ((dst >> 16) & 0xFF) * da / 255;
    uint8_t g = ((src >>  8) & 0xFF) * sa / 255 + ((dst >>  8) & 0xFF) * da / 255;
    uint8_t b = ((src      ) & 0xFF) * sa / 255 + ((dst      ) & 0xFF) * da / 255;
    return 0xFF000000 | (r << 16) | (g << 8) | b;
}

/* ── Color utilities ── */
uint32_t gfx_color_lerp(uint32_t a, uint32_t b, uint8_t t)
{
    uint8_t ra = (a >> 16) & 0xFF, ga = (a >> 8) & 0xFF, ba = a & 0xFF;
    uint8_t rb = (b >> 16) & 0xFF, gb = (b >> 8) & 0xFF, bb = b & 0xFF;
    return 0xFF000000 |
        ((ra + (((int)rb - ra) * t) / 255) << 16) |
        ((ga + (((int)gb - ga) * t) / 255) << 8)  |
        ( ba + (((int)bb - ba) * t) / 255);
}

uint32_t gfx_darken(uint32_t c, uint8_t amt)
{
    uint8_t r = ((c >> 16) & 0xFF) * (255 - amt) / 255;
    uint8_t g = ((c >>  8) & 0xFF) * (255 - amt) / 255;
    uint8_t b = ( c        & 0xFF) * (255 - amt) / 255;
    return 0xFF000000 | (r << 16) | (g << 8) | b;
}

uint32_t gfx_lighten(uint32_t c, uint8_t amt)
{
    uint8_t r = (c >> 16) & 0xFF, g = (c >> 8) & 0xFF, b = c & 0xFF;
    r = r + (amt * (255 - r)) / 255;
    g = g + (amt * (255 - g)) / 255;
    b = b + (amt * (255 - b)) / 255;
    return 0xFF000000 | (r << 16) | (g << 8) | b;
}

/* ── Clipped rectangle fill (fast path) ── */
void gfx_fill_rect(gfx_ctx_t* ctx, int32_t x, int32_t y, uint32_t w, uint32_t h, uint32_t c)
{
    if (!ctx || !ctx->fb || !w || !h) return;

    int32_t x0 = x, y0 = y;
    int32_t x1 = x + (int32_t)w;
    int32_t y1 = y + (int32_t)h;

    /* Clip to bounds */
    if (x0 < (int32_t)ctx->clip_x) x0 = (int32_t)ctx->clip_x;
    if (y0 < (int32_t)ctx->clip_y) y0 = (int32_t)ctx->clip_y;
    if (x1 > (int32_t)ctx->clip_x2) x1 = (int32_t)ctx->clip_x2;
    if (y1 > (int32_t)ctx->clip_y2) y1 = (int32_t)ctx->clip_y2;
    if (x0 >= x1 || y0 >= y1) return;

    uint32_t cw = (uint32_t)(x1 - x0);
    uint8_t a = c >> 24;

    if (a == 0xFF) {
        /* Opaque fast path */
        for (int32_t row = y0; row < y1; row++) {
            uint32_t* p = &ctx->fb[row * ctx->width + x0];
            for (uint32_t i = 0; i < cw; i++)
                p[i] = c;
        }
    } else if (a != 0) {
        /* Alpha blend */
        for (int32_t row = y0; row < y1; row++) {
            uint32_t* p = &ctx->fb[row * ctx->width + x0];
            for (uint32_t i = 0; i < cw; i++)
                p[i] = gfx_blend(p[i], c);
        }
    }
}

/* ── Rectangle outline ── */
void gfx_rect(gfx_ctx_t* ctx, int32_t x, int32_t y, uint32_t w, uint32_t h, uint32_t c)
{
    if (!ctx || !w || !h) return;
    gfx_fill_rect(ctx, x,     y,     w, 1, c);  /* top */
    gfx_fill_rect(ctx, x,     y+h-1, w, 1, c);  /* bottom */
    gfx_fill_rect(ctx, x,     y,     1, h, c);  /* left */
    gfx_fill_rect(ctx, x+w-1, y,     1, h, c);  /* right */
}

/* ── Bresenham line ── */
void gfx_line(gfx_ctx_t* ctx, int32_t x0, int32_t y0, int32_t x1, int32_t y1, uint32_t c)
{
    if (!ctx) return;

    int32_t dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int32_t dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int32_t sx = (x0 < x1) ? 1 : -1;
    int32_t sy = (y0 < y1) ? 1 : -1;
    int32_t err = dx - dy;

    while (1) {
        gfx_putpixel(ctx, x0, y0, c);
        if (x0 == x1 && y0 == y1) break;
        int32_t e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 <  dx) { err += dx; y0 += sy; }
    }
}

/* ── Rounded rectangle fill ── */
void gfx_fill_rounded(gfx_ctx_t* ctx, int32_t x, int32_t y, uint32_t w, uint32_t h, uint32_t r, uint32_t c)
{
    if (!ctx || !w || !h) return;
    if (r == 0) { gfx_fill_rect(ctx, x, y, w, h, c); return; }
    if (r > h/2) r = h/2;
    if (r > w/2) r = w/2;

    /* Fill center + straight edges */
    gfx_fill_rect(ctx, x+r, y, w-2*r, h, c);
    gfx_fill_rect(ctx, x, y+r, w, h-2*r, c);

    /* Four corner circles */
    gfx_fill_circle(ctx, x+r,     y+r,     r, c);
    gfx_fill_circle(ctx, x+w-r-1, y+r,     r, c);
    gfx_fill_circle(ctx, x+r,     y+h-r-1, r, c);
    gfx_fill_circle(ctx, x+w-r-1, y+h-r-1, r, c);
}

/* ── Rounded rectangle outline ── */
void gfx_rounded_rect(gfx_ctx_t* ctx, int32_t x, int32_t y, uint32_t w, uint32_t h, uint32_t r, uint32_t c)
{
    if (!ctx || !w || !h) return;
    if (r == 0) { gfx_rect(ctx, x, y, w, h, c); return; }
    if (r > h/2) r = h/2;
    if (r > w/2) r = w/2;

    /* Straight lines */
    gfx_line(ctx, x+r, y,     x+w-r, y,     c);
    gfx_line(ctx, x+r, y+h-1, x+w-r, y+h-1, c);
    gfx_line(ctx, x,     y+r, x,     y+h-r, c);
    gfx_line(ctx, x+w-1, y+r, x+w-1, y+h-r, c);

    /* Four corner arcs - drawn with simple 8-way symmetry */
    int r0 = (int)r;
    for (int cx_off = 0; cx_off <= r0; cx_off++) {
        int cy_off = (int)sqrt_int(r0*r0 - cx_off*cx_off);
        /* Top-left arc (90-180 degrees) */
        gfx_putpixel(ctx, x + r0 - cx_off,     y + r0 - cy_off, c);
        gfx_putpixel(ctx, x + r0 - cy_off,     y + r0 - cx_off, c);
        /* Top-right arc (0-90 degrees) */
        gfx_putpixel(ctx, x + (int)w - r0 + cx_off - 1, y + r0 - cy_off, c);
        gfx_putpixel(ctx, x + (int)w - r0 + cy_off - 1, y + r0 - cx_off, c);
        /* Bottom-left arc (180-270 degrees) */
        gfx_putpixel(ctx, x + r0 - cx_off,     y + (int)h - r0 + cy_off - 1, c);
        gfx_putpixel(ctx, x + r0 - cy_off,     y + (int)h - r0 + cx_off - 1, c);
        /* Bottom-right arc (270-360 degrees) */
        gfx_putpixel(ctx, x + (int)w - r0 + cx_off - 1, y + (int)h - r0 + cy_off - 1, c);
        gfx_putpixel(ctx, x + (int)w - r0 + cy_off - 1, y + (int)h - r0 + cx_off - 1, c);
    }
}

/* Integer square root - Babylonian method */
static int sqrt_int(int x)
{
    if (x <= 0) return 0;
    int res = x;
    int nx = (res + x / res) / 2;
    while (nx < res) {
        res = nx;
        nx = (res + x / res) / 2;
    }
    return res;
}

/* ── Circle fill (midpoint) ── */
void gfx_fill_circle(gfx_ctx_t* ctx, int32_t cx, int32_t cy, uint32_t r, uint32_t c)
{
    if (!ctx || !r) return;
    int32_t x = (int32_t)r;
    int32_t y = 0;
    int32_t d = 1 - (int32_t)r;

    while (y <= x) {
        gfx_fill_rect(ctx, cx - x, cy + y, 2 * (uint32_t)x + 1, 1, c);
        gfx_fill_rect(ctx, cx - x, cy - y, 2 * (uint32_t)x + 1, 1, c);
        gfx_fill_rect(ctx, cx - y, cy + x, 2 * (uint32_t)y + 1, 1, c);
        gfx_fill_rect(ctx, cx - y, cy - x, 2 * (uint32_t)y + 1, 1, c);
        y++;
        if (d < 0) {
            d += 2 * y + 1;
        } else {
            x--;
            d += 2 * (y - x) + 1;
        }
    }
}

/* ── Circle outline ── */
void gfx_circle(gfx_ctx_t* ctx, int32_t cx, int32_t cy, uint32_t r, uint32_t c)
{
    if (!ctx || !r) return;
    int32_t x = (int32_t)r, y = 0;
    int32_t d = 1 - (int32_t)r;

    while (y <= x) {
        gfx_putpixel(ctx, cx + x, cy + y, c);
        gfx_putpixel(ctx, cx + y, cy + x, c);
        gfx_putpixel(ctx, cx - y, cy + x, c);
        gfx_putpixel(ctx, cx - x, cy + y, c);
        gfx_putpixel(ctx, cx - x, cy - y, c);
        gfx_putpixel(ctx, cx - y, cy - x, c);
        gfx_putpixel(ctx, cx + y, cy - x, c);
        gfx_putpixel(ctx, cx + x, cy - y, c);
        y++;
        if (d < 0) {
            d += 2 * y + 1;
        } else {
            x--;
            d += 2 * (y - x) + 1;
        }
    }
}

/* ── Triangle fill ── */
void gfx_fill_triangle(gfx_ctx_t* ctx, int32_t x0, int32_t y0, int32_t x1, int32_t y1, int32_t x2, int32_t y2, uint32_t c)
{
    if (!ctx) return;

    /* Sort vertices by y */
    if (y0 > y1) { int32_t t=x0; x0=x1; x1=t; t=y0; y0=y1; y1=t; }
    if (y0 > y2) { int32_t t=x0; x0=x2; x2=t; t=y0; y0=y2; y2=t; }
    if (y1 > y2) { int32_t t=x1; x1=x2; x2=t; t=y1; y1=y2; y2=t; }

    /* Edge interpolation */
    int32_t dx01 = x1 - x0, dy01 = y1 - y0;
    int32_t dx02 = x2 - x0, dy02 = y2 - y0;
    int32_t dx12 = x2 - x1, dy12 = y2 - y1;

    int32_t x_left, x_right;

    for (int32_t y = y0; y <= y1; y++) {
        if (dy01 != 0) x_left  = x0 + (dx01 * (y - y0)) / dy01;
        else x_left = x0;
        if (dy02 != 0) x_right = x0 + (dx02 * (y - y0)) / dy02;
        else x_right = x0;
        if (x_left > x_right) { int32_t t=x_left; x_left=x_right; x_right=t; }
        gfx_fill_rect(ctx, x_left, y, (uint32_t)(x_right - x_left + 1), 1, c);
    }
    for (int32_t y = y1; y <= y2; y++) {
        if (dy12 != 0) x_left  = x1 + (dx12 * (y - y1)) / dy12;
        else x_left = x1;
        if (dy02 != 0) x_right = x0 + (dx02 * (y - y0)) / dy02;
        else x_right = x0;
        if (x_left > x_right) { int32_t t=x_left; x_left=x_right; x_right=t; }
        gfx_fill_rect(ctx, x_left, y, (uint32_t)(x_right - x_left + 1), 1, c);
    }
}

/* ── Gradient rectangle ── */
void gfx_gradient_rect(gfx_ctx_t* ctx, int32_t x, int32_t y, uint32_t w, uint32_t h, gradient_t* grad)
{
    if (!ctx || !grad || !w || !h) return;

    if (grad->vertical) {
        for (uint32_t row = 0; row < h; row++) {
            uint32_t c = gfx_color_lerp(grad->color1, grad->color2, (uint8_t)((row * 255) / (h - 1)));
            gfx_fill_rect(ctx, x, y + (int32_t)row, w, 1, c);
        }
    } else {
        for (uint32_t col = 0; col < w; col++) {
            uint32_t c = gfx_color_lerp(grad->color1, grad->color2, (uint8_t)((col * 255) / (w - 1)));
            gfx_fill_rect(ctx, x + (int32_t)col, y, 1, h, c);
        }
    }
}

void gfx_gradient_rounded(gfx_ctx_t* ctx, int32_t x, int32_t y, uint32_t w, uint32_t h, uint32_t r, gradient_t* grad)
{
    /* Simplified: gradient fill then rounded mask */
    gfx_gradient_rect(ctx, x, y, w, h, grad);
}

/* ── Text rendering ── */
void gfx_draw_text(gfx_ctx_t* ctx, int32_t x, int32_t y, const char* str, uint32_t color, uint32_t scale)
{
    if (!ctx || !str || !scale) return;
    if (scale > 4) scale = 4;

    int32_t cx = x;
    for (const char* p = str; *p; p++) {
        unsigned char ch = (unsigned char)*p;
        if (ch < 32 || ch > 126) ch = '?';

        const uint8_t* glyph = font_8x16[ch - 32];
        for (int row = 0; row < FONT_H; row++) {
            uint8_t row_bits = glyph[row];
            for (int col = 0; col < FONT_W; col++) {
                if (row_bits & (0x80 >> col)) {
                    if (scale == 1) {
                        gfx_putpixel(ctx, cx + col, y + row, color);
                    } else {
                        gfx_fill_rect(ctx, cx + col * (int32_t)scale,
                                           y + row * (int32_t)scale,
                                           scale, scale, color);
                    }
                }
            }
        }
        cx += (int32_t)(FONT_W * scale);
    }
}

void gfx_draw_text_center(gfx_ctx_t* ctx, int32_t cx, int32_t y, const char* str, uint32_t color, uint32_t scale)
{
    uint32_t tw = gfx_text_width(str, scale);
    gfx_draw_text(ctx, cx - (int32_t)(tw / 2), y, str, color, scale);
}

void gfx_draw_text_right(gfx_ctx_t* ctx, int32_t rx, int32_t y, const char* str, uint32_t color, uint32_t scale)
{
    uint32_t tw = gfx_text_width(str, scale);
    gfx_draw_text(ctx, rx - (int32_t)tw, y, str, color, scale);
}

uint32_t gfx_text_width(const char* str, uint32_t scale)
{
    if (!str || !scale) return 0;
    uint32_t len = (uint32_t)strlen(str);
    return len * FONT_W * scale;
}

/* ── Blit (copy) ── */
void gfx_blit(gfx_ctx_t* ctx, int32_t x, int32_t y, uint32_t w, uint32_t h, const uint32_t* src)
{
    if (!ctx || !src || !w || !h) return;

    int32_t x0 = x, y0 = y;
    int32_t x1 = x + (int32_t)w;
    int32_t y1 = y + (int32_t)h;
    int32_t sx = 0, sy = 0;

    if (x0 < (int32_t)ctx->clip_x) { sx += (int32_t)ctx->clip_x - x0; x0 = (int32_t)ctx->clip_x; }
    if (y0 < (int32_t)ctx->clip_y) { sy += (int32_t)ctx->clip_y - y0; y0 = (int32_t)ctx->clip_y; }
    if (x1 > (int32_t)ctx->clip_x2) x1 = (int32_t)ctx->clip_x2;
    if (y1 > (int32_t)ctx->clip_y2) y1 = (int32_t)ctx->clip_y2;
    if (x0 >= x1 || y0 >= y1) return;

    uint32_t cw = (uint32_t)(x1 - x0);
    for (int32_t row = y0; row < y1; row++) {
        uint32_t* dst = &ctx->fb[row * ctx->width + x0];
        const uint32_t* s = &src[(sy + (row - y0)) * w + sx];
        for (uint32_t i = 0; i < cw; i++)
            dst[i] = s[i];
    }
}

/* ── Blit with alpha ── */
void gfx_blit_alpha(gfx_ctx_t* ctx, int32_t x, int32_t y, uint32_t w, uint32_t h, const uint32_t* src)
{
    if (!ctx || !src || !w || !h) return;

    for (uint32_t row = 0; row < h; row++) {
        for (uint32_t col = 0; col < w; col++) {
            uint32_t c = src[row * w + col];
            if ((c >> 24) != 0)
                gfx_putpixel(ctx, x + (int32_t)col, y + (int32_t)row, c);
        }
    }
}

/* ── Blit with color key ── */
void gfx_blit_key(gfx_ctx_t* ctx, int32_t x, int32_t y, uint32_t w, uint32_t h, const uint32_t* src, uint32_t key)
{
    if (!ctx || !src || !w || !h) return;

    for (uint32_t row = 0; row < h; row++) {
        for (uint32_t col = 0; col < w; col++) {
            uint32_t c = src[row * w + col];
            if (c != key)
                gfx_putpixel(ctx, x + (int32_t)col, y + (int32_t)row, c);
        }
    }
}

/* ── Scaled blit (nearest-neighbor) ── */
void gfx_blit_scaled(gfx_ctx_t* ctx, int32_t dx, int32_t dy, uint32_t dw, uint32_t dh, const uint32_t* src, uint32_t sw, uint32_t sh)
{
    if (!ctx || !src || !dw || !dh || !sw || !sh) return;

    for (uint32_t y = 0; y < dh; y++) {
        uint32_t sy = (y * sh) / dh;
        for (uint32_t x = 0; x < dw; x++) {
            uint32_t sx = (x * sw) / dw;
            uint32_t c = src[sy * sw + sx];
            if ((c >> 24) != 0)
                gfx_putpixel(ctx, dx + (int32_t)x, dy + (int32_t)y, c);
        }
    }
}

/* ── Clip management ── */
void gfx_set_clip(gfx_ctx_t* ctx, uint32_t x, uint32_t y, uint32_t w, uint32_t h)
{
    if (!ctx) return;
    ctx->clip_x = x;
    ctx->clip_y = y;
    ctx->clip_x2 = x + w;
    if (ctx->clip_x2 > ctx->width) ctx->clip_x2 = ctx->width;
    ctx->clip_y2 = y + h;
    if (ctx->clip_y2 > ctx->height) ctx->clip_y2 = ctx->height;
}

void gfx_reset_clip(gfx_ctx_t* ctx)
{
    if (!ctx) return;
    ctx->clip_x = 0;
    ctx->clip_y = 0;
    ctx->clip_x2 = ctx->width;
    ctx->clip_y2 = ctx->height;
}

/* ── Context creation ── */
gfx_ctx_t* gfx_create_context(uint32_t* fb, uint32_t w, uint32_t h)
{
    static gfx_ctx_t ctx;
    ctx.fb = fb;
    ctx.width = w;
    ctx.height = h;
    ctx.pitch = w * 4;
    ctx.blend_mode = BLEND_ALPHA;
    gfx_reset_clip(&ctx);
    return &ctx;
}
